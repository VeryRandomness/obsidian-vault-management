import esbuild from "esbuild";
import process from "process";
import { builtinModules } from 'node:module';

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/VeryRandomness/obsidian-vault-management
*/
`;

const prod = (process.argv[2] === "production");

const common = {
	banner: {
		js: banner,
	},
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	minify: prod,
};

const mainCtx = await esbuild.context({ ...common, entryPoints: ["src/main.ts"], outfile: "main.js" });
// lib.js (the PDF libraries) is evaluated via new Function(), so it must not require anything external.
const libCtx = await esbuild.context({
	...common,
	entryPoints: ["src/features/pdfLib.ts"],
	outfile: "lib.js",
	external: [],
	platform: "browser",
	banner: {},
});

if (prod) {
	await Promise.all([mainCtx.rebuild(), libCtx.rebuild()]);
	process.exit(0);
} else {
	await Promise.all([mainCtx.watch(), libCtx.watch()]);
}
